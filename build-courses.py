def parse_frontmatter(text, fname):
    """The small YAML subset the course files use: key: value, "quoted", [lists], # comments."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise CourseError(f"{fname}:1: the file must start with a --- frontmatter block")
    meta, lines_of = {}, {}
    for i in range(1, len(lines)):
        raw = lines[i]
        if raw.strip() == "---":
            return meta, lines_of, i + 1          # i+1 = index of the first body line
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", raw)
        if not m:
            raise CourseError(f"{fname}:{i+1}: can't read this frontmatter line: {raw.strip()}")
        key, val = m.group(1), m.group(2).strip()
        if val.startswith('"'):
            q = re.match(r'"((?:[^"\\]|\\.)*)"', val)
            if not q:
                raise CourseError(f"{fname}:{i+1}: {key} has an unclosed quote")
            val = json.loads('"' + q.group(1) + '"')
        elif val.startswith("'"):
            q = re.match(r"'((?:[^']|'')*)'", val)
            if not q:
                raise CourseError(f"{fname}:{i+1}: {key} has an unclosed quote")
            val = q.group(1).replace("''", "'")
        elif val.startswith("["):
            body = re.sub(r"\]\s*(#.*)?$", "]", val)
            try:
                val = json.loads(body.replace("'", '"'))
            except ValueError:
                raise CourseError(f"{fname}:{i+1}: {key} should be a list like [\"A\", \"B\"]")
        else:
            val = re.sub(r"\s+#.*$", "", val).strip()
        meta[key], lines_of[key] = val, i + 1
    raise CourseError(f"{fname}: the frontmatter block is never closed with ---")


def parse_date(val, fname, line, key):
    try:
        return datetime.date.fromisoformat(str(val))
    except ValueError:
        raise CourseError(f"{fname}:{line}: {key} must be a date like 2026-11-04 (got {val!r})")


def parse_duration(val, fname, line):
    m = re.fullmatch(r"PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", str(val))
    if not m or not any(m.groups()):
        raise CourseError(f"{fname}:{line}: duration must be ISO 8601 like PT42M15S (got {val!r})")
    h, mi, s = (int(x or 0) for x in m.groups())
    return h * 3600 + mi * 60 + s


def parse_stamp(val):
    """'12:34' or '1:02:03' -> seconds, or None if malformed."""
    m = re.fullmatch(r"(\d{1,3}):([0-5]\d)", val) or re.fullmatch(r"(\d+):([0-5]\d):([0-5]\d)", val)
    if not m:
        return None
    parts = [int(x) for x in m.groups()]
    return parts[0] * 60 + parts[1] if len(parts) == 2 else parts[0] * 3600 + parts[1] * 60 + parts[2]


def clock(sec):
    h, rem = divmod(int(sec), 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def runtime(sec):
    mins = max(1, round(sec / 60))
    return f"{mins // 60} hr {mins % 60} min" if mins >= 60 else f"{mins} min"


def stamp(d):
    """Google wants a time and time zone on schema dates: noon in Columbus keeps the calendar date right everywhere."""
    from zoneinfo import ZoneInfo
    return datetime.datetime(d.year, d.month, d.day, 12, tzinfo=ZoneInfo("America/New_York")).isoformat()


def nice_date(d):
    return f"{MONTHS[d.month - 1]} {d.day}, {d.year}"


def load_course(md_path):
    fname = os.path.relpath(md_path, HERE)
    stem = os.path.basename(md_path)[:-3]
    text = open(md_path, encoding="utf-8").read().replace("\r\n", "\n")
    meta, at, body_start = parse_frontmatter(text, fname)
    errors = []

    def err(msg):
        errors.append(msg)

    for k in REQUIRED:
        if not str(meta.get(k, "")).strip():
            err(f"{fname}:{at.get(k, 1)}: required field '{k}' is missing or empty")
    if errors:
        raise CourseError("\n".join(errors))

    c = {"src": md_path, "fname": fname, "title": meta["title"].strip(), "slug": meta["slug"].strip(),
         "description": meta["description"].strip(), "youtube_id": meta["youtube_id"].strip(),
         "thumbnail": str(meta.get("thumbnail", "") or "").strip(), "tags": meta.get("tags") or [],
         "sponsors": meta.get("sponsor_domains") or []}
    if c["slug"] != stem:
        err(f"{fname}:{at['slug']}: slug '{c['slug']}' must match the filename ('{stem}')")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", c["slug"]):
        err(f"{fname}:{at['slug']}: slug may use only lowercase letters, numbers and single hyphens")
    if not re.fullmatch(r"[A-Za-z0-9_-]{11}", c["youtube_id"]):
        err(f"{fname}:{at['youtube_id']}: youtube_id should be the 11-character video ID (got {c['youtube_id']!r})")
    n = len(c["description"])
    if not 150 <= n <= 160:
        err(f"{fname}:{at['description']}: description is {n} characters; it must be 150 to 160")
    if isinstance(c["sponsors"], str):
        c["sponsors"] = [c["sponsors"]]
    c["sponsors"] = [re.sub(r"^(https?://)?(www\.)?", "", str(d)).strip("/ ").lower() for d in c["sponsors"]]
    if not all(re.fullmatch(r"[a-z0-9.-]+\.[a-z]{2,}", d) for d in c["sponsors"]):
        err(f"{fname}:{at.get('sponsor_domains', 1)}: sponsor_domains must be domains like [\"leadsimple.com\"]")
    if not isinstance(c["tags"], list) or not all(isinstance(t, str) for t in c["tags"]):
        err(f"{fname}:{at.get('tags', 1)}: tags must be a list of words like [\"Operations\", \"Pricing\"]")
    try:
        c["date"] = parse_date(meta["date"], fname, at["date"], "date")
        c["upload_date"] = parse_date(meta["upload_date"], fname, at["upload_date"], "upload_date")
        c["updated"] = parse_date(meta["updated"], fname, at["updated"], "updated") if meta.get("updated") else c["date"]
        c["duration_iso"] = meta["duration"]
        c["seconds"] = parse_duration(meta["duration"], fname, at["duration"])
    except CourseError as e:
        err(str(e))

    # whole-file checks: placeholders and dashes (both files)
    llm_path = md_path[:-3] + ".llm.md"
    files = [(fname, text)]
    if os.path.exists(llm_path):
        files.append((os.path.relpath(llm_path, HERE), open(llm_path, encoding="utf-8").read()))
    else:
        err(f"{fname}: the companion file {os.path.relpath(llm_path, HERE)} is missing")
    for fn, t in files:
        for ln, line in enumerate(t.split("\n"), 1):
            for p in PLACEHOLDERS:
                if p in line:
                    err(f"{fn}:{ln}: placeholder {p} is still in the file (the course is unfinished)")
            if "—" in line or "–" in line:
                err(f"{fn}:{ln}: em or en dash found; use a comma, colon, parentheses or a new sentence")

    # body: modules ({t=...} on H2s) and images
    body_lines = text.split("\n")[body_start:]
    modules, last = [], -1
    for i, line in enumerate(body_lines):
        ln = body_start + i + 1
        if re.match(r"^#\s", line):
            err(f"{fname}:{ln}: use ## for sections; the page title comes from the frontmatter")
        if "{t=" in line and not line.startswith("## "):
            err(f"{fname}:{ln}: only ## headings can carry a {{t=...}} timestamp")
        m = re.match(r"^##\s+(.*?)\s*\{t=([^}]*)\}\s*$", line)
        if line.startswith("## ") and "{t=" in line and not m:
            err(f"{fname}:{ln}: malformed timestamp marker; it must end the heading, like {{t=12:34}}")
        if m:
            sec = parse_stamp(m.group(2).strip())
            if sec is None:
                err(f"{fname}:{ln}: timestamp '{m.group(2)}' must be MM:SS or H:MM:SS")
                continue
            if sec <= last:
                err(f"{fname}:{ln}: timestamp {m.group(2)} is not after the previous module's")
            if c.get("seconds") is not None and sec >= c["seconds"]:
                err(f"{fname}:{ln}: timestamp {m.group(2)} is past the end of the video ({clock(c['seconds'])})")
            modules.append({"title": m.group(1).strip(), "start": sec, "line": i})
            last = sec
        for im in re.finditer(r"!\[([^\]]*)\]\(", line):
            if not im.group(1).strip():
                err(f"{fname}:{ln}: an image has empty alt text; describe what it shows")
        for ref in re.findall(r"\]\(\s*<?(/[^)\s>]+)", line):
            local = ref.split("#")[0].split("?")[0]
            if local.startswith("/courses/assets/") and not os.path.exists(os.path.join(HERE, local.lstrip("/"))):
                err(f"{fname}:{ln}: {local} not found (put the file in courses/assets/{c['slug']}/)")
        cm = re.match(r"^\s*>\s*\[!([^\]]*)\](.*)$", line)
        if cm:
            kind = cm.group(1).strip().upper()
            if kind not in CALLOUTS and kind not in ("STAT", "VIDEO"):
                err(f"{fname}:{ln}: unknown component [!{cm.group(1)}]; use TAKEAWAY, WARNING, NOTE, STAT or VIDEO")
            elif kind == "VIDEO":
                vid_, bar, lab = cm.group(2).partition("|")
                if not re.fullmatch(r"[A-Za-z0-9_-]{11}", vid_.strip()) or not bar or not lab.strip():
                    err(f"{fname}:{ln}: a VIDEO needs a YouTube ID and a label, like > [!VIDEO] rphTnIq3SXQ | Watch me build it")
            elif kind == "STAT":
                val, bar, lab = cm.group(2).partition("|")
                if not bar or not val.strip() or not lab.strip():
                    err(f"{fname}:{ln}: a STAT needs a value and a label, like > [!STAT] 8-12 | Numbers on a starting scorecard")
    if not modules:
        err(f"{fname}: no timed modules; mark each module heading like ## Setting your rate {{t=12:34}}")
    if c["thumbnail"] and c["thumbnail"].startswith("/") and not os.path.exists(os.path.join(HERE, c["thumbnail"].lstrip("/"))):
        err(f"{fname}:{at['thumbnail']}: thumbnail {c['thumbnail']} not found")
    if errors:
        raise CourseError("\n".join(errors))

    for i, mod in enumerate(modules):
        mod["end"] = modules[i + 1]["start"] if i + 1 < len(modules) else c["seconds"]
    c["modules"] = modules
    c["body_lines"] = body_lines
    c["llm_path"] = llm_path
    c["url"] = f"{SITE}/courses/{c['slug']}/"
    return c


