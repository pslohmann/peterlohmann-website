def main():
    os.makedirs(SRC, exist_ok=True)
    sources = sorted(f for f in os.listdir(SRC) if f.endswith(".md") and not f.endswith(".llm.md") and not f.startswith(("_", ".")) and f != "README.md")
    nav, foot, v = shell()
    built, failed, skipped_all = [], [], []
