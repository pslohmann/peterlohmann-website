def make_cover(c):
    """Returns (cover_path, card_path, width, height) as site paths. Re-downloads only when the source changes."""
    from PIL import Image
    folder = os.path.join(ASSETS, c["slug"])
    os.makedirs(folder, exist_ok=True)
    cover, card = os.path.join(folder, "_cover.jpg"), os.path.join(folder, "_card.webp")
    source = c["thumbnail"] or f"youtube:{c['youtube_id']}"
    stamp = os.path.join(folder, "_cover-source.txt")
    if os.path.exists(cover) and os.path.exists(card) and os.path.exists(stamp) and open(stamp).read() == source:
        w, h = Image.open(cover).size
        return f"/courses/assets/{c['slug']}/_cover.jpg", f"/courses/assets/{c['slug']}/_card.webp", w, h

    data = None
    if c["thumbnail"].startswith("/"):
        data = open(os.path.join(HERE, c["thumbnail"].lstrip("/")), "rb").read()
    elif c["thumbnail"]:
        data = fetch(c["thumbnail"])
    else:
        # The high-res thumbnail doesn't exist for every video; fall back to the next size down.
        for size in ("maxresdefault", "sddefault", "hqdefault"):
            try:
                d = fetch(f"https://i.ytimg.com/vi/{c['youtube_id']}/{size}.jpg")
                if Image.open(io.BytesIO(d)).size[0] > 200:
                    data = d
                    break
            except (urllib.error.URLError, OSError):
                continue
    if data is None:
        raise CourseError(f"{c['fname']}: couldn't get a thumbnail for video {c['youtube_id']} (offline?)")
    im = Image.open(io.BytesIO(data)).convert("RGB")
    w, h = im.size
    # crop to 16:9 (YouTube's smaller sizes are 4:3 with black bars top and bottom)
    if abs(w / h - 16 / 9) > 0.01:
        nh = round(w * 9 / 16)
        if nh <= h:
            top = (h - nh) // 2
            im = im.crop((0, top, w, top + nh))
        else:
            nw = round(h * 16 / 9)
            left = (w - nw) // 2
            im = im.crop((left, 0, left + nw, h))
    if im.size[0] > 1280:
        im = im.resize((1280, 720), Image.LANCZOS)
    im.save(cover, "JPEG", quality=86, optimize=True, progressive=True)
    im.resize((800, 450), Image.LANCZOS).save(card, "WEBP", quality=80, method=6)
    open(stamp, "w").write(source)
    w, h = im.size
    return f"/courses/assets/{c['slug']}/_cover.jpg", f"/courses/assets/{c['slug']}/_card.webp", w, h


