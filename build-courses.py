def inline_svg(src, alt):
    """A diagram's SVG markup, safe to paste into the page: no scripts, event handlers or outside
    references, and its ids prefixed with the file name so two diagrams can't clash. Inlined (not
    <img>) so the text uses the site font and stays readable to search engines."""
    root = ET.parse(os.path.join(HERE, src.lstrip("/"))).getroot()
    prefix = re.sub(r"[^a-z0-9]+", "-", os.path.basename(src)[:-4].lower()).strip("-")
    for parent in list(root.iter()):
        for child in list(parent):
            if child.tag.split("}")[-1] in ("script", "foreignObject", "iframe"):
                parent.remove(child)
    ids = {}
    for el in root.iter():
        for k in list(el.attrib):
            name, v = k.split("}")[-1].lower(), el.attrib[k]
            if name.startswith("on") or (name == "href" and not v.startswith("#")) or re.search(r"url\(\s*['\"]?(?!#)", v):
                del el.attrib[k]
        if "id" in el.attrib:
            ids[el.attrib["id"]] = f"{prefix}-{el.attrib['id']}"
            el.attrib["id"] = ids[el.attrib["id"]]
    for el in root.iter():
        for k, v in list(el.attrib.items()):
            nv = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#{ids.get(m.group(1), m.group(1))})", v)
            if k.split("}")[-1] == "href" and v.startswith("#"):
                nv = "#" + ids.get(v[1:], v[1:])
            if nv != v:
                el.attrib[k] = nv
    for a in ("width", "height"):
        root.attrib.pop(a, None)
    root.set("role", "img")
    root.set("aria-label", alt)
    root.set("focusable", "false")
    return ET.tostring(root, encoding="unicode")


def anchor(text, used):
    a = re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-")[:60] or "section"
    base, n = a, 2
    while a in used:
        a, n = f"{base}-{n}", n + 1
    used.add(a)
    return a


