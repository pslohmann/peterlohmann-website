INLINE = re.compile(
    r"(?P<code>`+)(?P<codetext>.+?)(?P=code)"
    r"|!\[(?P<ialt>[^\]]*)\]\(\s*<?(?P<isrc>[^)\s>]+)>?(?:\s+\"(?P<ititle>[^\"]*)\")?\s*\)"
    r"|\[(?P<ltext>(?:[^\[\]]|\[[^\]]*\])+)\]\(\s*<?(?P<lhref>[^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)"
    r"|\*\*(?P<b1>.+?)\*\*|__(?P<b2>.+?)__"
    r"|(?<![\w*])\*(?![\s*])(?P<i1>.+?)(?<![\s*])\*(?![\w*])"
    r"|(?<![\w_])_(?![\s_])(?P<i2>.+?)(?<![\s_])_(?![\w_])"
    r"|<(?P<auto>https?://[^>\s]+)>")


SPONSORS = set()   # the course being built's sponsor_domains (set in build_course)


def link_attrs(href):
    ext = re.match(r"https?://", href) and not re.match(r"https?://(www\.)?peterlohmann\.com", href)
    host = re.sub(r"^www\.", "", (re.match(r"https?://([^/:?#]+)", href) or [None, ""])[1].lower())
    if ext and any(host == d or host.endswith("." + d) for d in SPONSORS):
        return f' href="{esc(href)}" target="_blank" rel="sponsored noopener"'      # Google: label paid links
    if href.startswith("/courses/assets/") and not href.lower().endswith((".svg", ".jpg", ".jpeg", ".png", ".webp", ".gif")):
        return f' href="{esc(href)}" download data-track="course_download_click"'      # e.g. a PDF checklist
    return f' href="{esc(href)}"' + (' target="_blank" rel="noopener"' if ext else "")


def inline(s):
    out, pos = [], 0
    for m in INLINE.finditer(s):
        out.append(esc(s[pos:m.start()]).replace("&#x27;", "'"))
        pos = m.end()
        g = m.groupdict()
        if g["code"]:
            out.append(f"<code>{esc(g['codetext'])}</code>")
        elif g["isrc"]:
            t = f' title="{esc(g["ititle"])}"' if g["ititle"] else ""
            out.append(f'<img src="{esc(g["isrc"])}" alt="{esc(g["ialt"])}"{t} loading="lazy" />')
        elif g["lhref"]:
            out.append(f"<a{link_attrs(g['lhref'])}>{inline(g['ltext'])}</a>")
        elif g["b1"] is not None or g["b2"] is not None:
            out.append(f"<strong>{inline(g['b1'] if g['b1'] is not None else g['b2'])}</strong>")
        elif g["i1"] is not None or g["i2"] is not None:
            out.append(f"<em>{inline(g['i1'] if g['i1'] is not None else g['i2'])}</em>")
        elif g["auto"]:
            out.append(f"<a{link_attrs(g['auto'])}>{esc(g['auto'])}</a>")
    out.append(esc(s[pos:]).replace("&#x27;", "'"))
    return "".join(out)


LIST_RE = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")
TABLE_SEP = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$")


def split_row(line):
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", line)]


def render_list(lines, i, steps=False):
    """Render a (possibly nested) list starting at lines[i]. Returns (html, next_index).
    steps=True turns a top-level numbered list into step cards (used inside timed modules)."""
    first = LIST_RE.match(lines[i])
    indent = len(first.group(1).expandtabs(4))
    ordered = first.group(2)[0].isdigit()
    start = int(re.match(r"\d+", first.group(2)).group()) if ordered else 1
    items = []
    while i < len(lines):
        m = LIST_RE.match(lines[i])
        if not m or len(m.group(1).expandtabs(4)) != indent or m.group(2)[0].isdigit() != ordered:
            if m and len(m.group(1).expandtabs(4)) > indent and items:
                sub, i = render_list(lines, i)
                items[-1][1].append(sub)
                continue
            if lines[i].strip() and items and not m and (lines[i].startswith(" ") or lines[i].startswith("\t")):
                items[-1][0].append(lines[i].strip())       # indented continuation line
                i += 1
                continue
            if not lines[i].strip() and i + 1 < len(lines):
                nxt = LIST_RE.match(lines[i + 1])
                if nxt and len(nxt.group(1).expandtabs(4)) >= indent and items:
                    i += 1                                   # blank line inside the same list
                    continue
            break
        items.append([[m.group(3)], []])
        i += 1
    tag = "ol" if ordered else "ul"
    attr = f' start="{start}"' if ordered and start != 1 else ""
    if steps and ordered:
        li = "".join(f'<li><span class="step-num" aria-hidden="true">{start + k}</span><div class="step-body">{inline(" ".join(t))}{"".join(sub)}</div></li>'
                     for k, (t, sub) in enumerate(items))
        return f'<ol class="steps"{attr}>{li}</ol>', i
    li = "".join(f"<li>{inline(' '.join(t))}{''.join(sub)}</li>" for t, sub in items)
    return f"<{tag}{attr}>{li}</{tag}>", i


def md_to_html(lines, heading_hook=None, timed=None):
    """Block-level Markdown plus the course components. heading_hook(level, text, line_index) may
    return replacement HTML; timed(line_index) says whether an H2 starts a timed module (numbered
    lists inside timed modules become step cards)."""
    out, i, para = [], 0, []
    in_module = False

    def flush():
        if para:
            joined = " ".join(p.strip() for p in para)
            fig = re.fullmatch(r"!\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+\"([^\"]*)\")?\s*\)"
                               r"(?:\s+(?:\*([^*]+)\*|_([^_]+)_))?", joined)
            if fig:
                alt, src = fig.group(1), fig.group(2)
                cap_text = fig.group(3) or fig.group(4) or fig.group(5)
                cap = f"<figcaption>{inline(cap_text)}</figcaption>" if cap_text else ""
                if src.lower().endswith(".svg") and src.startswith("/"):
                    out.append(f'<figure class="cc-figure">{inline_svg(src, alt)}{cap}</figure>')
                else:
                    size = ""
                    local = os.path.join(HERE, src.lstrip("/")) if src.startswith("/") else ""
                    if local and os.path.exists(local):
                        from PIL import Image
                        w, h = Image.open(local).size
                        size = f' width="{w}" height="{h}"'
                        tall = ' class="tall"' if h > w * 1.2 else ""      # portrait screenshots: keep them a readable size
                    else:
                        tall = ""
                    out.append(f'<figure{tall}><img src="{esc(src)}" alt="{esc(alt)}"{size} loading="lazy" decoding="async" />{cap}</figure>')
            else:
                out.append(f"<p>{inline(joined)}</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        if not line.strip():
            flush(); i += 1; continue
        if line.startswith("```"):
            flush()
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre><code>" + esc("\n".join(lines[i + 1:j])) + "</code></pre>")
            i = j + 1; continue
        h = re.match(r"^(#{2,4})\s+(.*?)\s*#*\s*$", line)
        if h:
            flush()
            level, text = len(h.group(1)), h.group(2)
            if level == 2:
                in_module = bool(timed and timed(i))
            custom = heading_hook(level, text, i) if heading_hook else None
            out.append(custom if custom is not None else f"<h{level}>{inline(text)}</h{level}>")
            i += 1; continue
        if line.strip().lower().startswith("<details"):
            flush()
            j = i
            while j < len(lines) and "</details>" not in lines[j].lower():
                j += 1
            block = "\n".join(lines[i:j + 1])
            dm = re.search(r"<summary>(.*?)</summary>(.*)</details>", block, re.S | re.I)
            summary, inner = (dm.group(1).strip(), dm.group(2)) if dm else ("More", "")
            out.append(f'<details class="cc-details"><summary>{inline(summary)}</summary>'
                       f'<div class="cc-details-body">{md_to_html(inner.strip().split(chr(10)))}</div></details>')
            i = j + 1; continue
        if re.fullmatch(r"\s*(?:-{3,}|\*{3,}|_{3,})\s*", line):
            flush(); out.append("<hr />"); i += 1; continue
        if line.lstrip().startswith(">"):
            flush()
            quote = []
            while i < len(lines) and lines[i].lstrip().startswith(">"):
                quote.append(re.sub(r"^\s*>\s?", "", lines[i])); i += 1
            cm = re.match(r"\[!(\w+)\]\s*(.*)$", quote[0].strip()) if quote else None
            if cm and cm.group(1).upper() == "STAT":
                val, _, lab = cm.group(2).partition("|")
                stat = (f'<div class="cc-stat"><span class="cc-stat-num">{inline(val.strip())}</span>'
                        f'<span class="cc-stat-label">{inline(lab.strip())}</span></div>')
                if out and out[-1].startswith('<div class="cc-stats">'):
                    out[-1] = out[-1][:-len("</div>")] + stat + "</div>"     # stats in a row sit side by side
                else:
                    out.append('<div class="cc-stats">' + stat + "</div>")
                continue
            if cm and cm.group(1).upper() == "VIDEO":
                vid_, _, lab = cm.group(2).partition("|")
                vid_, lab = vid_.strip(), lab.strip()
                out.append(f'<figure class="cc-video"><a class="course-player" href="https://www.youtube.com/watch?v={vid_}" data-id="{vid_}" '
                           f'target="_blank" rel="noopener" aria-label="Play the video: {esc(lab)}">'
                           f'<img src="https://i.ytimg.com/vi/{vid_}/hqdefault.jpg" alt="" width="480" height="360" loading="lazy" />'
                           f'<span class="ep-play" aria-hidden="true"></span><span class="yt-label">{YT_ICON}Watch on YouTube</span></a>'
                           f'<figcaption>{inline(lab)}</figcaption></figure>')
                continue
            if cm and cm.group(1).upper() in CALLOUTS:
                kind = cm.group(1).upper()
                body = md_to_html(([cm.group(2)] if cm.group(2).strip() else []) + quote[1:])
                out.append(f'<div class="cc cc-{kind.lower()}"><p class="cc-label">{CALLOUTS[kind]}</p>{body}</div>')
                continue
            out.append("<blockquote>" + md_to_html(quote) + "</blockquote>"); continue
        if "|" in line and i + 1 < len(lines) and TABLE_SEP.match(lines[i + 1]):
            flush()
            head = split_row(line)
            rows = []
            i += 2
            while i < len(lines) and "|" in lines[i] and lines[i].strip():
                rows.append(split_row(lines[i])); i += 1
            th = "".join(f"<th>{inline(c)}</th>" for c in head)
            tb = "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in rows)
            out.append(f'<div class="post-table-wrap"><table class="post-table"><thead><tr>{th}</tr></thead><tbody>{tb}</tbody></table></div>')
            continue
        if LIST_RE.match(line) and not para:
            flush()
            block, i = render_list(lines, i, steps=in_module)
            out.append(block); continue
        para.append(line[:-2] + "<br>" if line.endswith("  ") else line)
        i += 1
    flush()
    return "\n".join(out).replace("&lt;br&gt;", "<br />")


