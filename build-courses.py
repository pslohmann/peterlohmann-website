def update_llms(courses):
    p = os.path.join(HERE, "llms.txt")
    if not os.path.exists(p):
        return
    s = open(p, encoding="utf-8").read()
    s = re.sub(r"\n## Free Courses\n.*?(?=\n## |\Z)", "", s, flags=re.S)       # drop the old section
    if courses:
        lines = [f"- [{c['title']}]({SITE}/courses/{c['slug']}.llm.md): {c['description']}" for c in courses]
        sec = "\n## Free Courses\n\n" + "\n".join(lines) + "\n"
        if "\n## About and contact" in s:
            s = s.replace("\n## About and contact", sec + "\n## About and contact", 1)
        else:
            s = s.rstrip("\n") + "\n" + sec
    open(p, "w", encoding="utf-8").write(s)


